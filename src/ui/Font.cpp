const unsigned char* Font::glyph(char c) {
    if (c >= 'a' && c <= 'z' && c != 'x') c = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    for (const G& g : kGlyphs) if (g.c == c) return g.r;
    return kBlank;
}

